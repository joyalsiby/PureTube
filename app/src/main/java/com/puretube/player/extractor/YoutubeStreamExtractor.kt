data class AudioTrackOption(
    val id: String,             // Unique track identifier (e.g. "en.original", "es.dubbed", "default")
    val label: String,          // User-facing label (e.g. "English (Original)", "Spanish (Dubbed)")
    val audioUrl: String,
    val isOriginal: Boolean,
    val languageCode: String?,
    val bitrate: Int,
    val dashManifestXml: String? = null
)

data class CaptionOption(
    val id: String,             // Unique caption identifier (e.g. "en_manual", "en_auto")
    val label: String,          // User-facing label (e.g. "English", "English (Auto-generated)")
    val languageCode: String,
    val url: String,
    val mimeType: String,       // MimeTypes.TEXT_VTT or MimeTypes.APPLICATION_TTML
    val isAutoGenerated: Boolean
)

data class VideoQualityOption(
    val label: String,          // e.g., "1080p60", "720p", "360p"
    val resolutionHeight: Int,  // e.g., 1080, 720
    val fps: Int = 30,
    val codec: String? = null,
    val videoUrl: String,
    val isVideoOnly: Boolean,   // true if requires separate audio stream merging
    val audioUrl: String?,      // default/original audio stream URL when isVideoOnly is true
    val dashManifestXml: String? = null
)

data class ExtractedVideo(
    val videoId: String,
    val originalUrl: String,
    val title: String,
    val uploaderName: String,
    val thumbnailUrl: String,
    val durationSeconds: Long,
    val description: String = "",
    val viewCount: Long = -1L,
    val uploadDate: String = "",
    val likeCount: Long = -1L,
    val hlsUrl: String?,
    val dashUrl: String?,
    val bestAudioUrl: String?,
    val qualities: List<VideoQualityOption>,
    val audioTracks: List<AudioTrackOption>,
    val captions: List<CaptionOption>
)

object YoutubeStreamExtractor {

    /**
     * Extracts clean YouTube URL or Video ID from arbitrary shared text
     * (e.g. "Check out this video: https://youtu.be/dQw4w9WgXcQ?si=1234")
     */
    fun extractYoutubeUrl(rawInput: String): String? {
        val trimmed = rawInput.trim()
        if (trimmed.isEmpty()) return null

        // Regex matching standard watch, short, embed, live, or youtu.be URLs
        val urlPattern = Pattern.compile(
            "(https?://(?:www\\.|m\\.)?(?:youtube\\.com/(?:watch\\?[^\\s]*v=|shorts/|embed/|live/)|youtu\\.be/)([a-zA-Z0-9_-]{11})[^\\s]*)",
            Pattern.CASE_INSENSITIVE
        )
        val matcher = urlPattern.matcher(trimmed)
        if (matcher.find()) {
            val videoId = matcher.group(2)
            if (!videoId.isNullOrEmpty()) {
                return "https://www.youtube.com/watch?v=$videoId"
            }
        }

        // Also support pasting just the 11-character video ID directly
        if (trimmed.matches(Regex("^[a-zA-Z0-9_-]{11}$"))) {
            return "https://www.youtube.com/watch?v=$trimmed"
        }

        return null
    }

    suspend fun extractStream(rawUrlOrText: String): Result<ExtractedVideo> = withContext(Dispatchers.IO) {
        runCatching {
            val cleanUrl = extractYoutubeUrl(rawUrlOrText)
                ?: throw IllegalArgumentException("Please enter a valid YouTube video link.")

            val youtubeService = ServiceList.YouTube
            // Use StreamExtractor directly instead of StreamInfo.getInfo() to skip unnecessary
            // secondary network calls (related videos, comments, channel subscriber counts, etc.)
            // for significantly faster video loading!
            val extractor = youtubeService.getStreamExtractor(cleanUrl)
            extractor.fetchPage()

            val videoId = runCatching { extractor.id }.getOrDefault("")
            val title = runCatching { extractor.name }.getOrDefault("YouTube Video").ifBlank { "YouTube Video" }
            val uploaderName = runCatching { extractor.uploaderName }.getOrDefault("YouTube").ifBlank { "YouTube" }
            val durationSeconds = runCatching { extractor.length }.getOrDefault(0L).coerceAtLeast(0L)
            val viewCount = runCatching { extractor.viewCount }.getOrDefault(-1L)
            val likeCount = runCatching { extractor.likeCount }.getOrDefault(-1L)
            val uploadDate = runCatching { extractor.textualUploadDate }.getOrNull()?.trim().orEmpty()
            val rawDescription = runCatching { extractor.description?.content }.getOrNull().orEmpty()
            val cleanDescription = formatDescriptionText(rawDescription)
            val streamType = runCatching { extractor.streamType }.getOrDefault(StreamType.VIDEO_STREAM)
            val hlsUrl = if (streamType == StreamType.LIVE_STREAM) {
                runCatching { extractor.hlsUrl }.getOrNull()?.takeIf { it.isNotBlank() }
            } else {
                runCatching { extractor.hlsUrl }.getOrNull()?.takeIf { it.isNotBlank() }
            }
            val dashUrl = runCatching { extractor.dashMpdUrl }.getOrNull()?.takeIf { it.isNotBlank() }

            val rawAudioStreams = runCatching { extractor.audioStreams }.getOrDefault(emptyList())
                .filter { it.content.isNotEmpty() && it.isUrl }

            // Group audio streams by language/track so we can offer YouTube's multi-language audio switch
            // (e.g., Original vs English Dubbed vs Spanish, etc.) and always default to Original.
            val audioTracks = buildAudioTrackOptions(rawAudioStreams, durationSeconds)

            // Default audio is ALWAYS the original track (or first sorted track)
            val defaultAudioTrack = audioTracks.firstOrNull { it.isOriginal } ?: audioTracks.firstOrNull()
            val bestAudioUrl = defaultAudioTrack?.audioUrl

            val qualityMap = linkedMapOf<String, VideoQualityOption>()

            // 1. Adaptive Video-only streams (1080p, 1440p, 4K, 720p60, 480p, 360p, etc.)
            // Using adaptive streams paired with audioTracks allows switching audio tracks at ANY resolution!
            val videoOnlyStreams = runCatching { extractor.videoOnlyStreams }.getOrDefault(emptyList())
            if (bestAudioUrl != null) {
                videoOnlyStreams
                    .filter { it.content.isNotEmpty() && it.isUrl }
                    // Strictly prioritize hardware-decoded AVC1 (H.264) -> VP9 -> AV1 first to avoid software decoding heat
                    .sortedWith(
                        compareByDescending<VideoStream> { parseHeight(it.resolution) }
                            .thenByDescending { videoCodecRank(it.codec) }
                            .thenBy { if (it.fps in 1..30) 0 else 1 } // Prefer 30fps over 60fps when sharing the same label
                            .thenByDescending { it.format?.suffix.equals("mp4", ignoreCase = true) }
                    )
                    .forEach { stream ->
                        val res = stream.resolution.ifEmpty { "${stream.height}p" }
                        if (res.isNotEmpty() && !qualityMap.containsKey(res)) {
                            val dashManifest = buildDashManifestForVideo(stream, durationSeconds)
                            qualityMap[res] = VideoQualityOption(
                                label = res,
                                resolutionHeight = parseHeight(res),
                                fps = stream.fps.takeIf { it > 0 } ?: 30,
                                codec = stream.codec,
                                videoUrl = stream.content,
                                isVideoOnly = true,
                                audioUrl = bestAudioUrl,
                                dashManifestXml = dashManifest
                            )
                        }
                    }
            }

            // 2. Muxed Video+Audio streams (fallback if adaptive stream for a resolution isn't present)
            val muxedStreams = runCatching { extractor.videoStreams }.getOrDefault(emptyList())
            muxedStreams
                .filter { it.content.isNotEmpty() && it.isUrl }
                .sortedByDescending { parseHeight(it.resolution) }
                .forEach { stream ->
                    val res = stream.resolution.ifEmpty { "${stream.height}p" }
                    if (res.isNotEmpty() && !qualityMap.containsKey(res)) {
                        qualityMap[res] = VideoQualityOption(
                            label = res,
                            resolutionHeight = parseHeight(res),
                            fps = stream.fps.takeIf { it > 0 } ?: 30,
                            codec = stream.codec,
                            videoUrl = stream.content,
                            isVideoOnly = false,
                            audioUrl = null,
                            dashManifestXml = null
                        )
                    }
                }

            val sortedQualities = qualityMap.values.sortedWith(
                compareByDescending<VideoQualityOption> { it.resolutionHeight }
                    .thenByDescending { it.fps }
            )

            if (sortedQualities.isEmpty() && hlsUrl.isNullOrEmpty()) {
                throw IllegalStateException("No playable video streams found for this video.")
            }

            // Kick off parallel RAM preloading of the default startup video + audio stream prefixes
            // immediately while the UI transitions to VideoPlayerScreen!
            val startupQuality = selectDefaultStartupQuality(sortedQualities)
            YoutubeStreamPreloader.preloadStreams(
                videoUrl = startupQuality?.videoUrl,
                audioUrl = bestAudioUrl
            )

            // Extract subtitles / closed captions (prefer WebVTT for clean Media3 rendering, fallback to TTML)
            val captions = extractCaptions(extractor)

            val bestThumbnail = runCatching {
                extractor.thumbnails.maxByOrNull { it.height * it.width }?.url
            }.getOrNull()
                ?.takeIf { it.isNotBlank() }
                ?: "https://i.ytimg.com/vi/$videoId/hqdefault.jpg"

            ExtractedVideo(
                videoId = videoId,
                originalUrl = cleanUrl,
                title = title,
                uploaderName = uploaderName,
                thumbnailUrl = bestThumbnail,
                durationSeconds = durationSeconds,
                description = cleanDescription,
                viewCount = viewCount,
                uploadDate = uploadDate,
                likeCount = likeCount,
                hlsUrl = hlsUrl,
                dashUrl = dashUrl,
                bestAudioUrl = bestAudioUrl,
                qualities = sortedQualities,
                audioTracks = audioTracks,
                captions = captions
            )
        }
    }

    fun selectDefaultStartupQuality(qualities: List<VideoQualityOption>): VideoQualityOption? {
        if (qualities.isEmpty()) return null
        // Prefer 30fps hardware-decoded AVC1 (H.264) at 1080p or 720p first for cool, battery-friendly playback,
        // avoiding 60fps or AV1 software-decoded streams unless explicitly chosen by the user.
        return qualities.firstOrNull {
            it.resolutionHeight == 1080 && it.fps <= 30 && it.codec?.startsWith("avc", ignoreCase = true) == true
        } ?: qualities.firstOrNull {
            it.resolutionHeight == 720 && it.fps <= 30 && it.codec?.startsWith("avc", ignoreCase = true) == true
        } ?: qualities.firstOrNull {
            it.resolutionHeight == 1080 && it.fps <= 30 && !it.codec.orEmpty().startsWith("av01", ignoreCase = true)
        } ?: qualities.firstOrNull {
            it.resolutionHeight == 720 && it.fps <= 30 && !it.codec.orEmpty().startsWith("av01", ignoreCase = true)
        } ?: qualities.firstOrNull {
            it.resolutionHeight == 1080 && it.codec?.startsWith("avc", ignoreCase = true) == true
        } ?: qualities.firstOrNull {
            it.resolutionHeight == 720
        } ?: qualities.firstOrNull {
            it.resolutionHeight <= 1080
        } ?: qualities.firstOrNull()
    }

    private fun videoCodecRank(codec: String?): Int {
        val c = codec?.lowercase().orEmpty()
        return when {
            c.startsWith("avc") -> 3            // H.264: universal hardware decoder, lowest startup latency
            c.startsWith("vp9") || c.startsWith("vp09") -> 2 // VP9: hardware decoded on modern Android
            c.startsWith("av01") -> 1           // AV1: often software decoded, higher initial CPU spike
            else -> 0
        }
    }

    private fun buildDashManifestForVideo(stream: VideoStream, durationSeconds: Long): String? {
        if (!stream.isUrl && stream.deliveryMethod == DeliveryMethod.DASH) {
            return stream.content.takeIf { it.isNotBlank() }
        }
        val itag = stream.itagItem ?: return null
        if (itag.initStart < 0 || itag.initEnd < 0 || itag.indexStart < 0 || itag.indexEnd < 0) {
            return null
        }
        return runCatching {
            YoutubeProgressiveDashManifestCreator.fromProgressiveStreamingUrl(
                stream.content,
                itag,
                durationSeconds.coerceAtLeast(1L)
            )
        }.getOrNull()?.takeIf { it.isNotBlank() }
    }

    private fun buildDashManifestForAudio(stream: AudioStream, durationSeconds: Long): String? {
        if (!stream.isUrl && stream.deliveryMethod == DeliveryMethod.DASH) {
            return stream.content.takeIf { it.isNotBlank() }
        }
        val itag = stream.itagItem ?: return null
        if (itag.initStart < 0 || itag.initEnd < 0 || itag.indexStart < 0 || itag.indexEnd < 0) {
            return null
        }
        return runCatching {
            YoutubeProgressiveDashManifestCreator.fromProgressiveStreamingUrl(
                stream.content,
                itag,
                durationSeconds.coerceAtLeast(1L)
            )
        }.getOrNull()?.takeIf { it.isNotBlank() }
    }

    private fun buildAudioTrackOptions(
        streams: List<AudioStream>,
        durationSeconds: Long
    ): List<AudioTrackOption> {
        if (streams.isEmpty()) return emptyList()

        // Group streams by unique track identity (trackId, or locale+trackType, or "default")
        val grouped = streams.groupBy { stream ->
            val trackId = stream.audioTrackId?.trim().orEmpty()
            val lang = stream.audioLocale?.language?.trim().orEmpty()
            val typeName = stream.audioTrackType?.name.orEmpty()
            when {
                trackId.isNotEmpty() -> trackId
                lang.isNotEmpty() || typeName.isNotEmpty() -> "${lang}_${typeName}"
                else -> "default_original"
            }
        }

        val hasExplicitOriginal = streams.any {
            it.audioTrackType == AudioTrackType.ORIGINAL ||
                it.audioTrackName?.contains("original", ignoreCase = true) == true
        }

        val options = grouped.map { (groupKey, groupStreams) ->
            // Within each language/track group, pick the best stream (prefer M4A/MP4A AAC around 128kbps for fastest hardware decode & buffer fill)
            val bestStream = groupStreams.sortedWith(
                compareByDescending<AudioStream> {
                    it.format == MediaFormat.M4A || it.format?.suffix.equals("m4a", ignoreCase = true)
                }.thenByDescending {
                    it.averageBitrate in 96..192
                }.thenByDescending {
                    it.averageBitrate
                }
            ).first()

            val trackType = bestStream.audioTrackType
            val rawTrackName = bestStream.audioTrackName?.trim().orEmpty()
            val locale = bestStream.audioLocale
            val localeDisplay = locale?.getDisplayName(Locale.getDefault())
                ?.replaceFirstChar { if (it.isLowerCase()) it.titlecase(Locale.getDefault()) else it.toString() }
                .orEmpty()

            val isOriginal = when {
                trackType == AudioTrackType.ORIGINAL -> true
                rawTrackName.contains("original", ignoreCase = true) -> true
                !hasExplicitOriginal && groupKey == "default_original" -> true
                !hasExplicitOriginal && grouped.size == 1 -> true
                else -> false
            }

            val baseName = when {
                rawTrackName.isNotEmpty() -> rawTrackName
                localeDisplay.isNotEmpty() -> localeDisplay
                else -> "Original Audio"
            }

            val cleanLabel = buildString {
                append(baseName)
                if (isOriginal && !baseName.contains("original", ignoreCase = true)) {
                    append(" (Original)")
                } else if (trackType == AudioTrackType.DUBBED && !baseName.contains("dub", ignoreCase = true)) {
                    append(" (Dubbed)")
                } else if (trackType == AudioTrackType.DESCRIPTIVE && !baseName.contains("descriptive", ignoreCase = true)) {
                    append(" (Descriptive)")
                }
            }

            AudioTrackOption(
                id = groupKey,
                label = cleanLabel,
                audioUrl = bestStream.content,
                isOriginal = isOriginal,
                languageCode = locale?.language,
                bitrate = bestStream.averageBitrate,
                dashManifestXml = buildDashManifestForAudio(bestStream, durationSeconds)
            )
        }

        // If none was marked original (e.g. YouTube didn't tag AudioTrackType.ORIGINAL on the primary track),
        // mark the first non-dubbed track as Original so we always default to original audio.
        val normalizedOptions = if (options.none { it.isOriginal } && options.isNotEmpty()) {
            val firstNonDubIndex = options.indexOfFirst {
                !it.label.contains("dubbed", ignoreCase = true) &&
                    !it.label.contains("descriptive", ignoreCase = true)
            }.takeIf { it >= 0 } ?: 0

            options.mapIndexed { index, opt ->
                if (index == firstNonDubIndex) {
                    val updatedLabel = if (!opt.label.contains("original", ignoreCase = true)) {
                        "${opt.label} (Original)"
                    } else {
                        opt.label
                    }
                    opt.copy(isOriginal = true, label = updatedLabel)
                } else {
                    opt
                }
            }
        } else {
            options
        }

        // Sort so Original is ALWAYS first, followed by manual/dubbed tracks alphabetically
        return normalizedOptions.sortedWith(
            compareByDescending<AudioTrackOption> { it.isOriginal }
                .thenBy { it.label }
        )
    }

    private fun extractCaptions(extractor: org.schabi.newpipe.extractor.stream.StreamExtractor): List<CaptionOption> {
        val rawSubtitles = runCatching {
            extractor.getSubtitles(MediaFormat.VTT)
        }.getOrNull()?.takeIf { it.isNotEmpty() }
            ?: runCatching {
                extractor.subtitlesDefault
            }.getOrDefault(emptyList())

        val seenIds = mutableSetOf<String>()
        val result = mutableListOf<CaptionOption>()

        rawSubtitles
            .filter { it.content.isNotEmpty() }
            .forEach { sub ->
                val langTag = sub.languageTag.ifBlank { sub.locale.language.ifBlank { "und" } }
                val isAuto = sub.isAutoGenerated
                val uniqueId = "${langTag}_${if (isAuto) "auto" else "manual"}"
                if (seenIds.add(uniqueId)) {
                    val baseLang = sub.displayLanguageName.ifBlank {
                        sub.locale.getDisplayName(Locale.getDefault()).ifBlank { langTag }
                    }
                    val label = if (isAuto && !baseLang.contains("auto", ignoreCase = true)) {
                        "$baseLang (Auto-generated)"
                    } else {
                        baseLang
                    }
                    val format = sub.format
                    val mimeType = when (format) {
                        MediaFormat.VTT -> "text/vtt"
                        MediaFormat.SRT -> "application/x-subrip"
                        else -> "application/ttml+xml"
                    }
                    result.add(
                        CaptionOption(
                            id = uniqueId,
                            label = label,
                            languageCode = langTag,
                            url = sub.content,
                            mimeType = mimeType,
                            isAutoGenerated = isAuto
                        )
                    )
                }
            }

        // Sort manual captions first, then auto-generated, alphabetically
        return result.sortedWith(
            compareBy<CaptionOption> { it.isAutoGenerated }
                .thenBy { it.label }
        )
    }

    private fun parseHeight(resolution: String): Int {
        val match = Regex("(\\d{3,4})p").find(resolution)
        return match?.groupValues?.getOrNull(1)?.toIntOrNull() ?: 0
    }

    private fun formatDescriptionText(raw: String): String {
        if (raw.isBlank()) return ""
        val withLineBreaks = raw
            .replace(Regex("(?i)<br\\s*/?>"), "\n")
            .replace(Regex("(?i)</p>"), "\n\n")
        val decoded = runCatching {
            Html.fromHtml(withLineBreaks, Html.FROM_HTML_MODE_COMPACT).toString()
        }.getOrDefault(withLineBreaks)
        return decoded
            .replace(Regex("\n{3,}"), "\n\n")
            .trim()
    }
}
